// Builds ../../legacy.js — the app script from index.html (<script id="app">) compiled to ES5,
// bundled with the polyfills old browsers need (Promise, fetch, Object.assign, padStart, …).
// Run after every change to index.html:  cd tools/legacy && npm install && npm run build
const fs = require('fs');
const path = require('path');
const babel = require('@babel/core');
const esbuild = require('esbuild');
const acorn = require('acorn');

const root = path.resolve(__dirname, '../..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const m = html.match(/<script id="app">([\s\S]*?)<\/script>/);
if (!m) throw new Error('script#app not found in index.html');

// the app script starts with a guard that stops it when the legacy build should run instead — drop it here
let app = m[1].replace(/^\s*if\(window\.__legacy\)throw[^\n]*\n/m, '');

const targets = { chrome: '38', safari: '9', firefox: '40', ios: '9', samsung: '4' };
const compiled = babel.transformSync(app, {
  babelrc: false, configFile: false, sourceType: 'script', compact: false,
  presets: [[require.resolve('@babel/preset-env'), {
    targets, modules: false, useBuiltIns: 'usage', corejs: '3.39', loose: true,
    exclude: ['web.dom-collections.iterator'],
  }]],
}).code;

// polyfills that usage-detection can't see (fetch, regenerator for async/await)
const entry =
  "import 'regenerator-runtime/runtime';\nimport 'whatwg-fetch';\n" +
  compiled.replace(/^"use strict";?/, '');
const tmp = path.join(__dirname, '.entry.js');
fs.writeFileSync(tmp, entry);
const out = esbuild.buildSync({
  entryPoints: [tmp], bundle: true, write: false, minify: true, format: 'iife',
  target: 'es5', supported: { arrow: false, 'const-and-let': false, 'template-literal': false, destructuring: false },
  logLevel: 'error', absWorkingDir: __dirname,
});
fs.unlinkSync(tmp);
const code = '/* BellBoard legacy build — generated by tools/legacy/build.js, do not edit */\nwindow.__legacyRun=true;\ntry{\n' +
  out.outputFiles[0].text +
  '\n}catch(e){console.error(e);if(window.__legacyFail)window.__legacyFail();}\n';

// make sure the result really is ES5
acorn.parse(code, { ecmaVersion: 5 });
fs.writeFileSync(path.join(root, 'legacy.js'), code);
console.log('legacy.js written:', (code.length / 1024).toFixed(1), 'KB, ES5 OK');
